// Voidrunner sound forge: renders every designed layer to assets/audio/fx and
// regenerates src/game/soundBankManifest.js.
//
//   node tools/audio/forge.mjs            render everything
//   node tools/audio/forge.mjs thump creak    render only the named recipes
//   node tools/audio/forge.mjs --wav          also keep WAVs under output/audio-forge
//
// Requires ffmpeg (libmp3lame). Output is deterministic: each recipe variant
// is seeded from its name, so re-running only changes files whose recipe changed.
import { spawnSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as d from './forge/dsp.mjs';
import combat from './forge/recipes-combat.mjs';
import cockpit from './forge/recipes-cockpit.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const outDir = join(root, 'assets', 'audio', 'fx');
const recipes = { ...combat, ...cockpit };
const args = process.argv.slice(2), keepWav = args.includes('--wav');
const only = args.filter((arg) => !arg.startsWith('--'));
const wavDir = keepWav ? join(root, 'output', 'audio-forge') : join(tmpdir(), `voidrunner-forge-${process.pid}`);
mkdirSync(outDir, { recursive: true }); mkdirSync(wavDir, { recursive: true });

const seedFor = (id, variant) => { let seed = 2166136261; for (const c of `${id}#${variant}`) seed = Math.imul(seed ^ c.charCodeAt(0), 16777619); return seed >>> 0; };
const unknown = only.filter((id) => !recipes[id]);
if (unknown.length) { console.error(`Unknown recipes: ${unknown.join(', ')}`); process.exit(1); }

let rendered = 0, seconds = 0;
for (const [id, recipe] of Object.entries(recipes)) {
    if (only.length && !only.includes(id)) continue;
    for (let variant = 0; variant < recipe.variants; variant += 1) {
        let signal = d.tidy(recipe.make(variant, d.makeRng(seedFor(id, variant))));
        if (recipe.mono) signal = d.toMono(signal);
        if (recipe.loop) signal = d.rollLoop(d.normalize(signal, recipe.peak ?? -3));
        else signal = d.normalize(d.fade(d.trimTail(signal, recipe.floor ?? -54, 0.03), 0.0015, 0.03), recipe.peak ?? -3);
        const channels = d.isStereo(signal) ? signal : [signal];
        for (const channel of channels) for (const value of channel) if (!Number.isFinite(value)) throw new Error(`${id}-${variant}: non-finite sample`);
        const wav = join(wavDir, `${id}-${variant}.wav`), mp3 = join(outDir, `${id}-${variant}.mp3`);
        d.writeWav(wav, signal);
        const encode = spawnSync('ffmpeg', ['-v', 'error', '-y', '-i', wav, '-codec:a', 'libmp3lame', '-q:a', channels.length > 1 ? '4' : '5', '-write_xing', '1', mp3]);
        if (encode.status !== 0) throw new Error(`ffmpeg failed for ${id}-${variant}: ${encode.stderr}`);
        rendered += 1; seconds += channels[0].length / d.SR;
    }
    process.stdout.write(`${id} `);
}
if (!keepWav) rmSync(wavDir, { recursive: true, force: true });

// The manifest always describes every recipe, even on a partial render.
const manifest = {};
for (const [id, recipe] of Object.entries(recipes)) {
    const entry = { files: Array.from({ length: recipe.variants }, (_, variant) => `fx/${id}-${variant}.mp3`), group: recipe.group };
    if (recipe.loop) {
        // Loop period = file length minus both rolls; measured from the recipe itself.
        const probe = d.tidy(recipe.make(0, d.makeRng(seedFor(id, 0))));
        entry.loop = [d.LOOP_ROLL, Number(((d.isStereo(probe) ? probe[0] : probe).length / d.SR).toFixed(5))];
    }
    manifest[id] = entry;
}
writeFileSync(join(root, 'src', 'game', 'soundBankManifest.js'),
    `// GENERATED by tools/audio/forge.mjs — do not edit. Designed layers in assets/audio/fx.\n// loop: [startSeconds, periodSeconds] inside the file (see dsp.rollLoop).\nexport const FORGED_SOUNDS = ${JSON.stringify(manifest, null, 1)};\n`);
const bytes = readdirSync(outDir).reduce((total, file) => total + statSync(join(outDir, file)).size, 0);
console.log(`\nRendered ${rendered} files (${seconds.toFixed(1)} s). assets/audio/fx is ${(bytes / 1048576).toFixed(2)} MB across ${readdirSync(outDir).length} files.`);
