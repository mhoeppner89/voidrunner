// npm run icons:pixelize — rasterises tools/icons/itemGlyphs.mjs into the
// generated src/game/itemSprites.js through headless Chrome's canvas.
import http from 'node:http';
import {readFile,writeFile} from 'node:fs/promises';
import {extname,join,normalize} from 'node:path';
import {chromium} from 'playwright';
const root=new URL('../..',import.meta.url).pathname;
const types={'.html':'text/html','.mjs':'text/javascript','.js':'text/javascript'};
const server=http.createServer(async(req,res)=>{try{const path=normalize(join(root,decodeURIComponent(new URL(req.url,'http://x').pathname)));if(!path.startsWith(root))throw 0;const data=await readFile(path);res.writeHead(200,{'content-type':types[extname(path)]??'application/octet-stream'});res.end(data);}catch{res.writeHead(404);res.end();}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const chrome=process.env.CHROME_PATH??'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser=await chromium.launch({headless:true,executablePath:chrome,args:['--no-sandbox','--disable-gpu-sandbox']});
try{
  const page=await browser.newPage();
  await page.goto(`http://127.0.0.1:${server.address().port}/tools/icons/pixelize.html`);
  const sprites=await page.waitForFunction(()=>window.sprites).then(h=>h.jsonValue());
  const body=JSON.stringify(sprites).replace(/\],"/g,'],\n"');
  await writeFile(join(root,'src/game/itemSprites.js'),`// GENERATED by \`npm run icons:pixelize\` from tools/icons/itemGlyphs.mjs — do not edit.\n// Each sprite: [palette (6-hex colours, concatenated), run-length 32×32 grid]. See itemIcons.js.\nexport const ITEM_SPRITES=${body};\n`);
  console.log('sprites',Object.keys(sprites.equipment).length,'equipment',Object.keys(sprites.commodity).length,'commodities');
}finally{await browser.close();server.close();}
